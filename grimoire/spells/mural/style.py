def _taskbar_options(look_id: str) -> dict:
    """The taskbar as it's set in the Taskbar tab, wearing this look."""
    saved = load_state().get("taskbar", {}).get("options") or {}
    return {**taskbar.DEFAULTS, **saved, "look": plasmastyle.LOOKS[look_id].name}


def _frame(p: QPainter, rect: QRectF, look, radius: float, s: float):
    """A popup or tooltip background as the look draws it (fill + hairline)."""
    path = QPainterPath()
    path.addRoundedRect(rect, radius, radius)
    for k in range(6):                                   # a soft drop shadow so it lifts off the panel/wallpaper
        shadow = QPainterPath()
        grow = (k + 1) * 3 * s * 2
        shadow.addRoundedRect(rect.adjusted(-grow, -grow + 4 * s, grow, grow + 4 * s), radius + grow, radius + grow)
        p.fillPath(shadow, QColor(0, 0, 0, 18))
    fill = QColor(look.fill)
    fill.setAlphaF(look.fill_opacity)
    if look.fill_opacity < 1:                           # what the blur behind does: wash the wallpaper out
        p.fillPath(path, QColor(128, 128, 128, 90))
    p.fillPath(path, fill)
    if look.stroke_opacity > 0 and look.stroke_width:
        line = QColor(look.stroke)
        line.setAlphaF(look.stroke_opacity)
        width = max(1.0, look.stroke_width * s * 2)
        inner = QPainterPath()
        inner.addRoundedRect(rect.adjusted(width / 2, width / 2, -width / 2, -width / 2), radius, radius)
        p.strokePath(inner, QPen(line, width))


def render(look_id: str, w=1280, h=720) -> QImage:
    """The desktop with the taskbar, an open launcher menu and a tooltip, all in this look."""
    look = plasmastyle.LOOKS[look_id]
    o = _taskbar_options(look_id)
    img = taskbar.render("dock", o, w, h)
    s = w / 2560
    thick = o["height"] * s
    gap = 8 * s if o["floating"] else 0
    ink = QColor(20, 20, 20) if look.light else QColor(232, 232, 232)
    muted = QColor(100, 100, 100) if look.light else QColor(150, 150, 150)
    sel = QColor(0, 0, 0, 30) if look.light else QColor(255, 255, 255, 34)
    p = QPainter(img)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    p.setRenderHint(QPainter.RenderHint.TextAntialiasing)

    # launcher menu above the dock's left end
    mw, mh = 720 * s, 820 * s
    bar_top = h - gap - thick
    menu = QRectF(w / 2 - 560 * s, bar_top - 16 * s - mh, mw, mh)
    radius = look.popup_radius * s * 2
    _frame(p, menu, look, radius, s)
    pad = 36 * s
    search = QRectF(menu.x() + pad, menu.y() + pad, mw - 2 * pad, 64 * s)
    box = QPainterPath()
    box.addRoundedRect(search, min(radius, search.height() / 2), min(radius, search.height() / 2))
    p.fillPath(box, QColor(0, 0, 0, 22) if look.light else QColor(255, 255, 255, 20))
    p.setFont(QFont("IBM Plex Sans", max(6, int(22 * s))))
    p.setPen(muted)
    p.drawText(search.adjusted(24 * s, 0, 0, 0), Qt.AlignmentFlag.AlignVCenter,
               tr("grimoire.spells.mural.style", "Type to search"))
    apps = (tr("grimoire.spells.mural.style", "Files"), tr("grimoire.spells.mural.style", "Terminal"),
            tr("grimoire.spells.mural.style", "Web Browser"), tr("grimoire.spells.mural.style", "Settings"),
            tr("grimoire.spells.mural.style", "Text Editor"), tr("grimoire.spells.mural.style", "Music"),
            tr("grimoire.spells.mural.style", "Grimoire Linux"))
    row = 82 * s
    top = search.bottom() + 28 * s
    for k, name in enumerate(apps):
        r = QRectF(menu.x() + pad / 2, top + k * row, mw - pad, row - 8 * s)
        if k == 1:
            hl = QPainterPath()
            hl.addRoundedRect(r, min(radius, 12 * s), min(radius, 12 * s))
            p.fillPath(hl, sel)
        icon = QRectF(r.x() + 22 * s, r.center().y() - 22 * s, 44 * s, 44 * s)
        p.setPen(Qt.PenStyle.NoPen)
        shade = 70 + (k * 23) % 90 if look.light else 150 + (k * 23) % 90
        p.setBrush(QColor(shade, shade, shade))
        p.drawRoundedRect(icon, 10 * s, 10 * s)
        p.setPen(ink)
        p.setFont(QFont("IBM Plex Sans", max(6, int(22 * s))))
        p.drawText(r.adjusted(90 * s, 0, 0, 0), Qt.AlignmentFlag.AlignVCenter, name)
    foot = QRectF(menu.x() + pad, menu.bottom() - pad - 40 * s, mw - 2 * pad, 40 * s)
    p.setPen(QPen(muted, max(1.0, 2 * s)))
    up = QPointF(0, 18 * s)
    p.drawLine(foot.topLeft() - up, foot.topRight() - up)
    p.setPen(muted)
    p.setFont(QFont("IBM Plex Sans", max(6, int(18 * s))))
    p.drawText(foot, Qt.AlignmentFlag.AlignVCenter, tr("grimoire.spells.mural.style", "Sleep · Restart · Shut Down"))

    # tooltip over a task icon, to the right of the menu
    tip_text = tr("grimoire.spells.mural.style", "Terminal — ~/Projects")
    p.setFont(QFont("IBM Plex Sans", max(6, int(20 * s))))
    tw = p.fontMetrics().horizontalAdvance(tip_text) + 48 * s
    tip = QRectF(w / 2 + 240 * s, bar_top - 28 * s - 64 * s, tw, 64 * s)
    _frame(p, tip, look, min(look.popup_radius, 8) * s * 2, s)
    p.setPen(ink)
    p.drawText(tip, Qt.AlignmentFlag.AlignCenter, tip_text)
    p.end()
    return img


class StyleTab(ScreenTab):
    key = "style"
    context = "grimoire.spells.mural.style"
    subtitle = tr_noop("grimoire.spells.mural.style", "The look of your taskbar, menus, popups and tooltips "
                       "(Plasma Style). Applies instantly.")
    apply_label = tr_noop("grimoire.spells.mural.style", "Apply style")
    store = ["plasma"]

    def designs(self):
        return DESIGNS + community_designs("plasma")

    def preview(self, design, o):
        return render(design.id)

    def thumbnail(self, design, o):
        """Cards zoom in on the menu and the panel under it."""
        return render(design.id, 2560, 1440).copy(400, 540, 1600, 900)

    def apply(self, design, o):
        if design.id.startswith("store:"):
            ident = community_entry(design.id)["ident"]
            run_tool(["plasma-apply-desktoptheme", ident], ok_if_already=True)
        else:
            plasmastyle.apply(design.id)
        return tr("grimoire.spells.mural.style", "Applied ✓")
