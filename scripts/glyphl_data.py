"""Build GlyphL's bundled data from the Unicode files of the build machine (run again after a Unicode update):

    python3 scripts/glyphl_data.py

    grimoire/spells/glyphl/blocks.py      the Unicode blocks (from Blocks.txt; Python's unicodedata has none)
    grimoire/spells/glyphl/emoji.tsv.gz   English emoji names, groups and keywords: the fallback for systems without
                                          Plasma's emoji dictionaries (from Plasma's en.dict = CLDR annotations,
                                          else emoji-test.txt without keywords)

At run time GlyphL prefers the system's own dictionaries (/usr/share/plasma/emoji/<lang>.dict), which carry the names
and keywords in every language.
"""
import gzip
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

OUT = ROOT / "grimoire" / "spells" / "glyphl"
UNICODE = Path("/usr/share/unicode")
GROUPS = {"Smileys & Emotion": 1, "People & Body": 2, "Component": 3, "Animals & Nature": 4, "Food & Drink": 5,
          "Travel & Places": 6, "Activities": 7, "Objects": 8, "Symbols": 9, "Flags": 10}


def blocks():
    rows = []
    for line in (UNICODE / "Blocks.txt").read_text().splitlines():
        line = line.split("#")[0].strip()
        if ";" in line:
            span, name = (s.strip() for s in line.split(";"))
            lo, hi = (int(x, 16) for x in span.split(".."))
            rows.append(f"    (0x{lo:04X}, 0x{hi:04X}, {name!r}),\n")
    head = [l for l in (UNICODE / "Blocks.txt").read_text().splitlines()[:1]]
    (OUT / "blocks.py").write_text(
        "# SPDX-License-Identifier: GPL-3.0-or-later\n"
        f'"""Unicode blocks (first, last, name), generated by scripts/glyphl_data.py from {head[0].lstrip("# ")}."""\n'
        "BLOCKS = (\n" + "".join(rows) + ")\n")
    return len(rows)


def from_test_file() -> list[tuple[str, int, str, list[str]]]:
    out, group = [], 0
    for line in (UNICODE / "emoji" / "emoji-test.txt").read_text().splitlines():
        if line.startswith("# group:"):
            group = GROUPS.get(line.split(":", 1)[1].strip(), 0)
        elif "; fully-qualified" in line and group != 3:
            seq = "".join(chr(int(c, 16)) for c in line.split(";")[0].split())
            name = line.split("#", 1)[1].strip().split(" ", 2)[2]       # "😀 E1.0 grinning face"
            out.append((seq, group, name, []))
    return out


def emoji():
    from grimoire.spells.glyphl import data          # after blocks.py exists
    found = data.dict_paths("en")
    rows = data.parse_dict(found[0]) if found else None
    rows = rows or from_test_file()
    lines = []
    for text, group, name, words in rows:
        if any(c in data.TONES for c in text):           # tone variants: GlyphL names them after their base
            lines.append(f"{text}\t{group}\t\t\n")
        else:
            words = [w for w in words if w and "\t" not in w and "|" not in w and w != name]
            lines.append(f"{text}\t{group}\t{name}\t{'|'.join(words)}\n")
    with gzip.open(OUT / "emoji.tsv.gz", "wt", encoding="utf-8", compresslevel=9) as f:
        f.writelines(lines)
    return len(lines), "Plasma en.dict" if found else "emoji-test.txt"


if __name__ == "__main__":
    print(f"{blocks()} blocks → blocks.py")
    n, src = emoji()
    print(f"{n} emoji from {src} → emoji.tsv.gz ({(OUT / 'emoji.tsv.gz').stat().st_size // 1024} KB)")
